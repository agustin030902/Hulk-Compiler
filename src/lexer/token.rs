#[derive(Clone, Debug, PartialEq)]
pub enum TokenKind {
    Identifier(String),
    Number(String),
    String(String),
    Boolean(String),
    Let,
    Function,
    Type,
    Protocol,
    Extends,
    New,
    While,
    For,
    Range,
    Print,
    Pi,
    E,
    Sin,
    Cos,
    Sqrt,
    Exp,
    Log,
    Rand,
    In,
    Null,
    Assign,
    Arrow,
    Add,
    Power,
    Concat,
    ConcatSpace,
    Minus,
    Multiply,
    Divide,
    EqualEqual,
    NotEqual,
    Less,
    Greater,
    LessEqual,
    GreaterEqual,
    And,
    Or,
    Not,
    DestructiveAssign,
    Colon,
    Comma,
    Semicolon,
    LeftBrace,
    RightBrace,
    LeftParen,
    RightParen,
    Dot,
    Unknown,
    EOF,
    If,
    Else,
    Elif,
    Inherits,
    Is,
    As,
}

#[derive(Clone, Debug)]
pub struct Token {
    pub kind: TokenKind,
    pub value: String,
    pub line: usize,
    pub column: usize,
    pub start: usize,
    pub end: usize,
}

impl Token {
    pub fn kind(&self) -> &TokenKind {
        &self.kind
    }
}
